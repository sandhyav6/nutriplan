<#
.SYNOPSIS
    One-time local setup WITHOUT Docker (Windows PowerShell 5.1+).

.DESCRIPTION
    * creates backend\.venv and installs the Python dependencies
    * creates backend\.env using a local SQLite database (unless backend\.env already exists)
    * applies the Alembic migrations and loads the illustrative food & recipe dataset
    * installs the frontend dependencies

    The SQLite files live in %LOCALAPPDATA%\NutriPlan - outside OneDrive, because syncing a
    live database file can lock or corrupt it. PostgreSQL remains the production database
    (see README - "Running without Docker" and OD-22).

    Safe to run again: existing files, packages and data are kept.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File scripts\setup-local.ps1
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$backend = Join-Path $root 'backend'
$frontend = Join-Path $root 'frontend'

function Step($text) { Write-Host "`n==> $text" -ForegroundColor Cyan }
function Invoke-Checked {
    param([string]$Exe, [string[]]$Arguments)
    & $Exe @Arguments
    if ($LASTEXITCODE -ne 0) { throw "Command failed ($LASTEXITCODE): $Exe $($Arguments -join ' ')" }
}

Step 'Checking prerequisites'
$python = Join-Path $backend '.venv\Scripts\python.exe'
if (-not (Test-Path $python)) {
    if (Get-Command py -ErrorAction SilentlyContinue) {
        Invoke-Checked 'py' @('-3.14', '-m', 'venv', (Join-Path $backend '.venv'))
    } elseif (Get-Command python -ErrorAction SilentlyContinue) {
        Invoke-Checked 'python' @('-m', 'venv', (Join-Path $backend '.venv'))
    } else {
        throw 'Python 3.14 was not found. Install it from https://www.python.org/downloads/ and run this script again.'
    }
}
if (-not (Get-Command npm -ErrorAction SilentlyContinue)) {
    throw 'Node.js / npm was not found. Install Node.js 22 LTS from https://nodejs.org/ and run this script again.'
}

Step 'Installing backend dependencies'
Invoke-Checked $python @('-m', 'pip', 'install', '--disable-pip-version-check', '-q', '-r', (Join-Path $backend 'requirements.txt'))

Step 'Configuring backend\.env'
$envFile = Join-Path $backend '.env'
if (Test-Path $envFile) {
    Write-Host 'backend\.env already exists - leaving it unchanged.'
} else {
    $dataDir = Join-Path $env:LOCALAPPDATA 'NutriPlan'
    try {
        New-Item -ItemType Directory -Force $dataDir | Out-Null
        $probe = Join-Path $dataDir '.nutriplan-write-test'
        [System.IO.File]::WriteAllText($probe, 'ok')
        Remove-Item -LiteralPath $probe -Force
    } catch {
        $dataDir = Join-Path $backend '.data'
        Write-Warning "Cannot write to %LOCALAPPDATA%\NutriPlan - using $dataDir instead."
        New-Item -ItemType Directory -Force $dataDir | Out-Null
    }
    $dbUrl = 'sqlite:///' + ((Join-Path $dataDir 'nutriplan.db') -replace '\\', '/')
    $testDbUrl = 'sqlite:///' + ((Join-Path $dataDir 'nutriplan_test.db') -replace '\\', '/')
    $content = @"
# Local development without Docker - generated by scripts/setup-local.ps1. Never commit this file.
# To use PostgreSQL instead, replace both URLs (see backend/.env.example).
APP_NAME=NutriPlan API
ENVIRONMENT=development
LOG_LEVEL=INFO
DATABASE_URL=$dbUrl
TEST_DATABASE_URL=$testDbUrl
CORS_ORIGINS=http://localhost:5173,http://127.0.0.1:5173
"@
    # UTF-8 without BOM so the first key is read correctly.
    [System.IO.File]::WriteAllText($envFile, $content, (New-Object System.Text.UTF8Encoding $false))
    Write-Host "Created backend\.env (database: $dataDir\nutriplan.db)"
}

Step 'Applying database migrations and loading the catalogue'
Push-Location $backend
try {
    Invoke-Checked $python @('-m', 'alembic', 'upgrade', 'head')
    Invoke-Checked $python @('-m', 'app.cli', 'seed-catalogue')
} finally {
    Pop-Location
}

Step 'Installing frontend dependencies'
Push-Location $frontend
try {
    if (Test-Path 'node_modules') { Write-Host 'node_modules already present - skipping npm ci.' }
    else { Invoke-Checked 'npm' @('ci', '--no-audit', '--no-fund') }
} finally {
    Pop-Location
}

Write-Host "`nSetup complete." -ForegroundColor Green
Write-Host 'Start the app:            .\start.cmd            (or double-click start.cmd)'
Write-Host 'Production-style (1 URL): .\start.cmd -Production'
Write-Host 'Optional administrator:   set NUTRIPLAN_ADMIN_EMAIL / NUTRIPLAN_ADMIN_PASSWORD, then'
Write-Host '                          cd backend; .\.venv\Scripts\python.exe -m app.cli create-admin'
